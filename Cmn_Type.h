#ifndef CMN_TYPE_H_
#define CMN_TYPE_H_


/*
****************************************************************************************************
*                                            头文件包含
****************************************************************************************************
*/

#include <stdint.h>


/*
****************************************************************************************************
*                                             公开类型
****************************************************************************************************
*/

/* 字符和布尔类型 */

/*
 * xbool 保留 unsigned char 表示，不具有 _Bool 的自动归一化语义。
 * 将一般整数结果转为布尔值时，应显式比较并赋值 xtrue 或 xfalse。
 */
typedef char xchar;             /**< 字符类型，不表示固定符号性的整数。 */
typedef unsigned char xbool;    /**< 布尔存储类型，合法值为 xfalse、xtrue。 */

/* 定宽整数类型 */

/*
 * 目标平台须提供以下全部定宽类型；不支持时应在平台适配中明确处理，
 * 不得退回位宽不确定的基本类型。
 * 替换原有 typedef 后应全量重编译，检查格式化输出和对外二进制接口，
 * 不假定底层整数类型及其 ABI 与旧定义完全相同。
 */
typedef uint8_t xint8u;
typedef int8_t xint8s;
typedef uint16_t xint16u;
typedef int16_t xint16s;
typedef uint32_t xint32u;
typedef int32_t xint32s;
typedef uint64_t xint64u;
typedef int64_t xint64s;

/* 浮点类型 */

typedef float xfloat;           /**< 精度和表示由目标工具链决定。 */
typedef double xdouble;         /**< 不保证与 xfloat 具有不同的精度。 */


/*
****************************************************************************************************
*                                            公开宏定义
****************************************************************************************************
*/

/*
 * 规范保留的基础布尔宏，不按普通项目宏重新命名。
 * 用于 C/C++ 表达式，不用于预处理器 #if 表达式。
 */
#define xfalse ((xbool)0U)
#define xtrue  ((xbool)1U)

#endif /* CMN_TYPE_H_ */
